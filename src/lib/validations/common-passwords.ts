/**
 * Returns true if the given password is on the common-passwords blocklist.
 * Case-insensitive: the input is lowercased before the membership check.
 */
export function isCommonPassword(pw: string): boolean {
  return COMMON_PASSWORDS.has(pw.toLowerCase());
}
